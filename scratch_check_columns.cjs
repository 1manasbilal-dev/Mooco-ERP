async function checkColumns() {
  const tables = ['inventory_logs', 'purchases', 'allocations', 'sales', 'production_batches', 'retail_closings', 'items'];
  for (const table of tables) {
    const { data, error } = await supabase.from(table).select('*').limit(1);
    if (error) {
      console.log(`Table ${table} error:`, error.message);
    } else {
      console.log(`Table ${table} sample keys:`, data && data[0] ? Object.keys(data[0]) : '(empty table)');
    }
  }
}

